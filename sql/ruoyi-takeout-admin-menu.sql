SET NAMES utf8mb4;

-- 1. 若依官网（外链）
UPDATE sys_menu SET visible = '1' WHERE menu_name = '若依官网';

-- 2. 部门管理 / 岗位管理
UPDATE sys_menu SET visible = '1' WHERE menu_id IN (103, 104);

-- 3. 系统工具 + 子菜单（表单构建 115 / 代码生成 116 / 系统接口 117）
UPDATE sys_menu SET visible = '1' WHERE menu_id IN (3, 115, 116, 117);

-- 4. 数据看板菜单（已上移为首页，隐藏原入口；按钮权限 5101 保留不影响接口鉴权）
UPDATE sys_menu SET visible = '1' WHERE menu_id = 5100;

-- 复查
SELECT menu_id, menu_name, parent_id, visible FROM sys_menu
WHERE menu_id IN (3, 4, 103, 104, 115, 116, 117, 5000, 5100) ORDER BY menu_id;
