--   1. 隐藏"若依官网"外链菜单
--   2. 隐藏"部门管理""岗位管理"（单店商家用不到）
--   3. 隐藏"系统工具"及其子菜单（表单构建/代码生成/系统接口）
--   4. 隐藏外卖管理下的"数据看板"菜单（看板已改为管理端首页，避免重复入口）
-- 说明：
--   - visible='1' 仅前端不显示，菜单与权限数据保留，随时可改回 visible='0' 恢复
--   - 保留"系统监控"（含定时任务 110，T12 每日库存初始化依赖它）
